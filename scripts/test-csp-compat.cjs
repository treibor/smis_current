const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({}, {codeGeneration: {strings:false, wasm:false}});
vm.runInContext(`window = globalThis;
  window.Function = function () { throw new Error('CSP blocked unmapped function'); };
  window.eval = function () { throw new Error('CSP blocked unmapped eval'); };
  window.Vaadin = {Flow: {loadOnDemand: chunk => chunk}};`, context);
vm.runInContext(fs.readFileSync('src/main/resources/META-INF/resources/security/csp-registry.js', 'utf8'), context);
vm.runInContext(fs.readFileSync('src/main/resources/META-INF/resources/security/csp-compat.js', 'utf8'), context);
assert.equal(vm.runInContext(`new Function("return window.Vaadin.Flow.loadOnDemand('chunk-ab12.js');")()`, context), 'chunk-ab12.js');
assert.equal(vm.runInContext(`new Function('$0', '$1', 'return $0.$connector.set($1)')({$connector:{set: x => x}}, 7)`, context), 7);
assert.equal(vm.runInContext(`new Function('event', 'element', 'return (event.clientX)')({clientX:42}, {})`, context), 42);
assert.throws(() => vm.runInContext(`new Function("return window.Vaadin.Flow.loadOnDemand('x');alert(1);//")`, context), /Unmapped CSP/);
assert.throws(() => vm.runInContext(`eval('alert(1)')`, context), /Unmapped CSP/);
assert.throws(() => vm.runInContext(`(function(){}).constructor('return 7')()`, context), /Code generation from strings disallowed/);
assert.throws(() => vm.runInContext(`new Function('$0', 'return $0.constructor()')`, context), /Unmapped CSP/);
assert.equal(vm.runInContext('eval(7)', context), 7);
console.log('PASS: mapped calls, chunk loading, fail-closed unknown code under strict CSP');
